/* Run against the development-only Expo design preview, never a financial API. */
const path=require('node:path');
const fs=require('node:fs');
const assert=require('node:assert/strict');
const {chromium,expect}=require('../apps/web/node_modules/@playwright/test');
const output=path.resolve(__dirname,'../.artifacts/mobile-redesign');
fs.mkdirSync(output,{recursive:true});
const base='http://localhost:8091/design-preview';

(async()=>{
  const browser=await chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,timezoneId:'Asia/Kolkata',reducedMotion:'reduce'});
  const page=await context.newPage();
  const errors=[];
  let apiCalls=0;
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')console.error('BROWSER:',message.text().slice(0,1600));});
  page.on('request',request=>{if(request.url().includes('/api/v1/'))apiCalls++;});
  const screenshot=async(name)=>{await page.evaluate(()=>document.fonts.ready);await page.screenshot({path:path.join(output,name+'.png'),animations:'disabled'});};
  try{
    await page.goto(base,{timeout:180000});
    await expect(page.getByText('Make room for more.',{exact:true})).toBeVisible({timeout:180000});
    await page.evaluate(()=>document.fonts.ready);
    await screenshot('01-overview');
    await page.getByRole('button',{name:'Hide account balances',exact:true}).click();
    await expect(page.getByText('••••••',{exact:true}).first()).toBeVisible();
    await page.getByRole('button',{name:'Show account balances',exact:true}).click();
    await page.getByRole('tab',{name:'Spending trend',exact:true}).click();
    await screenshot('02-spending-trend');
    await page.getByRole('tab',{name:'Wallets',exact:true}).click();
    await expect(page.getByText('All together now.',{exact:true})).toBeVisible();
    await screenshot('03-wallets');
    await page.getByRole('tab',{name:'Plan',exact:true}).click();
    await expect(page.getByText('A plan that fits.',{exact:true})).toBeVisible();
    await screenshot('04-budgets');
    await page.getByRole('tab',{name:'Activity',exact:true}).click();
    await expect(page.getByText('A little coffee break',{exact:true})).toBeVisible();
    await screenshot('05-activity');
    await page.getByRole('button',{name:'Add transaction',exact:true}).click();
    await expect(page.getByLabel('Amount in rupees')).toBeVisible();
    await page.getByLabel('Amount in rupees').fill('125.50');
    await page.getByLabel('What was it for?').fill('Lunch with a friend');
    await page.getByRole('button',{name:'Food & dining',exact:true}).click();
    await screenshot('06-expense-entry');
    await page.getByRole('button',{name:'Review entry',exact:true}).click();
    await expect(page.getByText('All in the details.',{exact:true})).toBeVisible();
    await expect(page.getByText('₹125.50',{exact:true})).toBeVisible();
    await screenshot('07-review');
    await page.getByRole('button',{name:'Confirm & save',exact:true}).click();
    await expect(page.getByText('Preview received 12550 paise as expense. Example data only; nothing was saved.',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Close',exact:true}).click();
    await page.getByRole('button',{name:'Back to editing',exact:true}).click();
    await page.getByLabel('Amount in rupees').fill('0');
    await page.getByRole('button',{name:'Review entry',exact:true}).click();
    await expect(page.getByText('Enter an amount greater than zero.',{exact:true})).toBeVisible();
    await page.getByLabel('Amount in rupees').fill('2000');
    await page.getByRole('tab',{name:'transfer',exact:true}).click();
    await page.getByRole('button',{name:'Pocket money',exact:true}).click();
    await page.getByRole('button',{name:'Review entry',exact:true}).click();
    await expect(page.getByText('To wallet',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Confirm & save',exact:true}).click();
    await expect(page.getByText('Preview received 200000 paise as transfer. Example data only; nothing was saved.',{exact:true})).toBeVisible();
    await page.goto(base+'?screen=login',{timeout:60000});
    await expect(page.getByText('Welcome back, you.',{exact:true})).toBeVisible({timeout:30000});
    await screenshot('08-sign-in');
    await page.getByLabel('Email address').fill('not-an-email');
    await page.getByLabel('Password',{exact:true}).fill('short');
    await page.getByRole('button',{name:/get you in/}).click();
    await expect(page.getByText('Use at least 12 characters.',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Show password',exact:true}).click();
    await expect(page.getByLabel('Password',{exact:true})).toHaveJSProperty('type','text');
    await page.getByRole('button',{name:/Join Morrowmint/}).click();
    await expect(page.getByLabel('What should we call you?')).toBeVisible();
    await screenshot('09-registration');
    await page.setViewportSize({width:360,height:800});
    await page.goto(base,{timeout:60000});
    await expect(page.getByText('Make room for more.',{exact:true})).toBeVisible();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'No horizontal document overflow at 360px');
    await screenshot('10-small-phone');
    await page.getByRole('button',{name:'Your profile and settings',exact:true}).click();
    await page.getByRole('button',{name:'Preview empty state',exact:true}).click();
    await expect(page.getByText('Start with what you have.',{exact:true})).toBeVisible();
    await screenshot('11-empty-state');
    assert.deepEqual(errors,[],'No runtime page errors');
    assert.equal(apiCalls,0,'Design preview must never call financial APIs');
    console.log('PASS: mobile navigation, charts, hidden balances, reviewed INR entry, transfer entry, invalid amounts, authentication validation, password toggle, empty state, 390px/360px layouts.');
    console.log('Screenshots: '+output);
  }catch(error){await page.screenshot({path:path.join(output,'failure.png')}).catch(()=>{});fs.writeFileSync(path.join(output,'failure.txt'),errors.join('\n')+'\n'+await page.locator('body').innerText().catch(()=>''));throw error;}finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
